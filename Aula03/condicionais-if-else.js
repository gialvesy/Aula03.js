// if - else - Condicionais
// As estruturas condicionais permitem executar diferentes blocos dependendo de uma condição

let idade = 17;
if (idade >= 18) {
    console.log("Você é maior de idade!")
} else {
    console.log ("Você é menor de idade");
}

